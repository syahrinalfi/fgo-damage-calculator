import type { Card } from "@atlasacademy/api-connector";
import type { NpLevel } from "../account/types.js";
import type { TrackedBuff } from "./buffLifecycle.js";
import type { BattleUnit } from "./unit.js";
import type { Wave, WaveEnemy } from "../quest/types.js";

/**
 * One fielded servant's live battle state (research/09 §1) — the static baseline stats
 * `BattleUnit` already models (`atk`/`className`/`attribute`/`traits`) plus everything
 * that mutates turn to turn: HP, NP gauge (`FULL_TD_POINT` units, research/04 §1),
 * buffs-as-`TrackedBuff[]` (turn/use expiry, not the bare `ActiveBuffInstance[]`
 * `BattleUnit` uses for a single already-resolved hit), and skill cooldowns. Front-line
 * vs. sub-member (research/00 §4) matters because only front-line servants can act/be
 * targeted; a sub-member's state is otherwise frozen (research/07 §4, confirmed by the
 * project owner — Order Change swaps in a servant's state unchanged).
 *
 * Command Seal count is deliberately **not** a field here — research/00 §6, confirmed by
 * the project owner: Command Seals are a Master-level (account-wide) resource, not
 * per-servant, so `BattleState.commandSealsRemaining` is the single shared counter.
 */
export interface ServantInstance extends Omit<BattleUnit, "activeBuffs"> {
  readonly servantId: number;
  readonly isFrontLine: boolean;
  /** This servant's 5-card deck composition (`Entity.cards`, research/03 §6.4/§6.5), in fixed slot order. */
  readonly cardTypes: readonly Card[];
  /**
   * Determines this servant's NP gauge accumulation cap (research/04 §5.2a, confirmed by
   * the project owner): 100% at level 1, 200% at levels 2-4, 300% at level 5 — see
   * `NP_GAUGE_CAP_BY_LEVEL` in `./turnLoop.js`. Distinct from the NP's own `gaugeCount`
   * (minimum gauge required to cast at all, research/04 §5.3, almost universally 1 bar).
   */
  readonly npLevel: NpLevel;
  readonly currentHp: number;
  readonly maxHp: number;
  /** Raw gauge units; `FULL_TD_POINT` (10000, `src/engine/constants.ts`) equals 100%. */
  readonly currentNpGauge: number;
  readonly activeBuffs: readonly TrackedBuff[];
  /** Turns remaining before each of the servant's 3 skill slots is usable again; 0 = ready. */
  readonly skillCooldowns: readonly [number, number, number];
  /**
   * This servant's critical-star weighting stat (`NiceServant.starAbsorb`, research/04
   * §6.2-6.3, confirmed identical to the raw `mstSvtLimit.criticalWeight` field) — how much
   * of each star generated by a landed hit this servant's hand-card slots tend to attract in
   * the crit-star weighted lottery (`./critStarLottery.js`), relative to other fielded
   * servants' own weight.
   */
  readonly criticalWeight: number;
}

/**
 * One dealt hand-card slot, tagged with which servant it currently resolves against —
 * research/07 §4, confirmed by the project owner: Order Change re-attributes a hand-card
 * slot's owning servant without changing the card's *type* or touching the card bag, so a
 * bare `Card` value (as this project originally modeled `BattleState.handCards`/`cardBag`)
 * can't represent a mid-turn ownership change. `servantId` is also what `resolvePlayCard`
 * (`./turnLoop.js`) checks `Action.playCard.servantId` against, closing the "acting servant
 * isn't checked against the card" gap that field's doc comment used to flag as still-open.
 */
export interface HandCard {
  readonly card: Card;
  readonly servantId: number;
}

/**
 * One in-wave enemy's live battle state — a mutable copy of a `WaveEnemy` (research/08,
 * `src/quest/types.ts`) tracking only what changes during the fight: current HP, buffs,
 * and NP-charge progress. Everything else (ATK, traits, skills, `npTurnLimit`'s own source
 * value) stays on the static `WaveEnemy` record this instance was built from; re-deriving
 * it here would duplicate data `BattleState` would then need to keep in sync across a
 * shift/call/change swap (research/08 §3-4) — out of scope for this increment, which does
 * not model swap resolution yet.
 */
export interface EnemyInstance extends Omit<BattleUnit, "activeBuffs"> {
  readonly npcId: number;
  readonly currentHp: number;
  readonly maxHp: number;
  readonly activeBuffs: readonly TrackedBuff[];
  /**
   * Turns of NP-charge progress accumulated so far, out of `npTurnLimit` — an enemy's NP
   * gauge is a fundamentally different mechanism from `ServantInstance.currentNpGauge`
   * (research/08-enemy-mechanics.md §5, confirmed by the project owner's own gameplay
   * knowledge, then live-verified against `QuestEnemy.chargeTurn`): a discrete integer
   * countdown that advances by exactly `+1` every turn regardless of cards/crits/buffs (no
   * formula), not a continuous formula-driven percentage. `advanceEnemyForEndTurn`
   * (`./turnLoop.js`) increments this by 1 per turn; reaching `npTurnLimit` resets it back
   * to `0` (a new cycle starts) and sets `readyToNp` below — see that field's own doc
   * comment for what is and isn't implemented at that point.
   */
  readonly currentNpTurns: number;
  /**
   * This enemy's own NP-charge countdown target (research/08 §5) — sourced from
   * `WaveEnemy.chargeTurn` (live-confirmed: `5` on NP-capable enemies, `0` on enemies with
   * no NP at all). Static for the fight, unlike `currentNpTurns` — mirrors the
   * `currentHp`/`maxHp` pairing shape already used above, not `ServantInstance`'s
   * level-derived `NP_GAUGE_CAP_BY_LEVEL` (an enemy's limit is a per-record value, not
   * derived from anything comparable to NP level).
   */
  readonly npTurnLimit: number;
  /**
   * This enemy's own base instant-death susceptibility (`QuestEnemy.deathRate`, research/08
   * §2) — a per-mille multiplier `applyInstantDeathEffect` (`./turnLoop.js`) folds into the
   * skill/NP's own `InstantDeathEffect.deathRate` roll, per the community-sourced formula
   * (firq.dev, cross-referenced against live buff-targeting data this session — **not**
   * live-tested by the project owner, the one tier below this project's strongest sourcing):
   * `finalChance = hitRate * (deathRate / 1000) * (1 + grant - resist + nonresist)`. Static
   * for the fight, same shape as `npTurnLimit` above — no `WaveEnemy`-construction pipeline
   * exists yet to source this from `QuestEnemy.deathRate` automatically (same caveat as
   * `npTurnLimit`'s own doc comment). Typical cited values by enemy rarity: Bronze 80%,
   * Silver 50%, Gold 20% (community-sourced, not primary-confirmed — a caller building an
   * `EnemyInstance` by hand without real quest data should pick a plausible default from
   * this range rather than defaulting to `0`, which would silently zero out every
   * `instantDeath` roll against that enemy).
   */
  readonly deathRate: number;
  /**
   * Set `true` by `advanceEnemyForEndTurn` (`./turnLoop.js`) the moment `currentNpTurns`
   * reaches `npTurnLimit` — a trigger **flag only**, added 2026-09-08. Nothing else in this
   * project reads or clears it yet: no enemy NP effect resolves against the servants, no
   * `Action` exists to represent "the enemy casts its NP." That's still the deliberately
   * out-of-scope "phase 2, enemy-attack simulation" (research/08 §5) — this field exists so
   * a caller building that phase later has something to check ("is this enemy ready right
   * now") without also having to re-derive the reset-and-cycle logic itself. Once set, stays
   * `true` indefinitely — `advanceEnemyForEndTurn` only ever sets it, never clears it, so a
   * future "resolve the enemy's attack" step is responsible for flipping it back to `false`
   * once it actually handles the cast.
   */
  readonly readyToNp: boolean;
}

/**
 * Everything that can change during a fight (research/09 §1). This increment models the
 * state shape only — HP/gauge/cooldown/buff/hand/bag/cost bookkeeping a turn-resolution
 * loop will read and write — not the `Action` discriminated union or the loop itself
 * (research/09 §1's `Action` type, §2's turn-resolution pipeline), which need their own
 * dedicated increment per the prior session's scope-discipline pattern.
 *
 * Every field here (and on `ServantInstance`/`EnemyInstance`) is `readonly`: research/09
 * §1 defines the simulator as a pure function `(BattleState, Action) → BattleState'`, and
 * the existing buff-state layer (`applyBuff`/`advanceTurnBuffs`/`consumeBuffUse`,
 * `../buffs/buffGroup.js`/`./buffLifecycle.js`) is already written as pure functions
 * returning new arrays rather than mutating in place — a mutable `BattleState` would
 * invite in-place writes that break that model once the turn loop lands.
 */
export interface BattleState {
  readonly waves: readonly Wave[];
  readonly currentWaveIndex: number;
  readonly currentTurn: number;
  readonly servants: readonly ServantInstance[];
  readonly enemies: readonly EnemyInstance[];
  /** This turn's drawn pool minus already-played cards (research/00 §4), each slot tagged with its owning servant (`HandCard`, research/07 §4). */
  readonly handCards: readonly HandCard[];
  /**
   * Not-yet-dealt cards from the current 3-turn draw cycle (research/03 §6.5, research/09
   * §1) — the 3 fielded servants' 15-card combined deck, dealt without replacement across
   * 3 turns, then reshuffled. See `buildCombinedCardDeck` (`./cardDeck.js`) to build the
   * 15-card deck and `drawCardBagHand` (`./cardBag.js`) to deal a turn's hand from it.
   * Each entry is a `HandCard` (card + owning servant) even while still in the bag — the
   * ownership tag only becomes meaningful once dealt into `handCards`, but keeping the same
   * shape end to end avoids a conversion step at deal time.
   */
  readonly cardBag: readonly HandCard[];
  /**
   * Crit stars generated last turn, allocated via this turn's weighted lottery (research/04
   * §6.2). Never accumulates past one turn (research/04 §6.3) — `resolveEndTurn`
   * (`./turnLoop.js`) resets this to 0 immediately after allocating it into `handCardStars`,
   * since a turn's leftover stars are simply discarded rather than carried to a third turn.
   */
  readonly starsCarried: number;
  /**
   * Each `handCards` slot's crit-star allocation for this turn (same length/order as
   * `handCards`), computed once at hand-draw time (`resolveEndTurn`, `./turnLoop.js`) via
   * `allocateCritStars`'s weighted lottery over `starsCarried` (research/04 §6.2). Kept as a
   * parallel array rather than a field on `HandCard` itself since the cardBag reuses the
   * `HandCard` shape for not-yet-dealt cards, which have no crit-star allocation of their
   * own — see that type's own doc comment. `resolvePlayCard` reads this to derive
   * `HitResolutionContext.isCrit` (`./critStarLottery.js`'s `critChanceForStars`/
   * `rollIsCrit`) instead of taking it as caller-supplied input.
   */
  readonly handCardStars: readonly number[];
  /**
   * Pending flat crit-chance bonus earned this turn from a Quick-led chain's first-card
   * bonus (research/06 §7.2/§7.4's "+20% critical chance for all 5 hand cards",
   * `CHAINBONUS_QUICK_CRIT_RATE`, `src/engine/constants.ts`), to take effect *next* turn —
   * mirrors `starsCarried`'s "earned this turn, spent/discarded next" lifecycle exactly:
   * `resolveEndTurn` (`./turnLoop.js`) copies this into `activeCritChanceBonus` for the
   * freshly-drawn hand, then resets this field to 0. Never touched mid-turn except by
   * `applyChainCompletionBonus` adding to it (a Quick-led chain only affects hand cards from
   * the *next* hand-draw onward, not the current turn's already-fixed hand).
   */
  readonly critChanceBonusCarried: number;
  /**
   * This turn's already-activated flat crit-chance bonus (research/06 §7.2/§7.4), applied
   * uniformly to *every* hand card's crit roll — unlike `handCardStars`, this is a single
   * scalar rather than a per-slot array, since the bonus is flat-for-all-cards rather than
   * lottery-allocated. Set once at hand-draw time (`resolveEndTurn`) from the previous
   * turn's `critChanceBonusCarried`; `resolvePlayCard` adds it to `critChanceForStars(stars)`
   * before rolling `isCrit` (`./critStarLottery.js`).
   */
  readonly activeCritChanceBonus: number;
  readonly fieldTraits: ReadonlySet<number>;
  readonly costSpent: number;
  readonly costBudget: number;
  /**
   * Master-level (account-wide) resource, not per-servant (research/00 §6, confirmed by
   * the project owner) — max 3, spent by `useCommandSeal` (`./turnLoop.js`): 1 to fill a
   * servant's NP gauge to 100%, 1 to heal a servant's HP to 100%, or all 3 at once to
   * revive every dead party member (also maxing their NP gauge).
   */
  readonly commandSealsRemaining: number;
  /** Directly-consecutive NPs cast this turn with no non-NP card played in between (research/04 §5.5's NP Chain Bonus); resets to 0 on any non-NP `playCard`. */
  readonly consecutiveNpChainCount: number;
  /**
   * Turns remaining before each of the Mystic Code's 3 skill slots is usable again; 0 =
   * ready — the account-wide equivalent of `ServantInstance.skillCooldowns` (research/07
   * §2/§4: a Mystic Code has the same 3-slot skill/cooldown shape as a servant).
   */
  readonly mysticCodeSkillCooldowns: readonly [number, number, number];
}

/** Builds the `BattleUnit` shape `resolveHit`/`resolveDamageInput` etc. expect from a `ServantInstance`. */
export function servantToBattleUnit(servant: ServantInstance): BattleUnit {
  return { atk: servant.atk, className: servant.className, attribute: servant.attribute, traits: servant.traits, activeBuffs: servant.activeBuffs };
}

/** Builds the `BattleUnit` shape `resolveHit`/`resolveDamageInput` etc. expect from an `EnemyInstance`. */
export function enemyToBattleUnit(enemy: EnemyInstance): BattleUnit {
  return { atk: enemy.atk, className: enemy.className, attribute: enemy.attribute, traits: enemy.traits, activeBuffs: enemy.activeBuffs };
}

/**
 * The `WaveEnemy`(`QuestEnemy`)-to-`EnemyInstance` constructor this project didn't have yet
 * — every other `EnemyInstance`-shaped fixture up to now (tests, and every "no construction
 * pipeline exists yet" caveat on `currentNpTurns`/`npTurnLimit`/`deathRate`'s own doc
 * comments) was hand-built. Used by `applyShiftTransitions` (`./turnLoop.js`, research/08
 * §4) to build the replacement `EnemyInstance` when a break-bar (`shift`) transition fires,
 * and is the natural place a future initial-wave-setup step would also call from.
 *
 * Field mapping, each already-resolved per research/01 §6.2 ("actual stat values for this
 * specific quest instance, already resolved — not raw growth curves the caller has to
 * interpolate"): `atk`/`hp` direct (`adjustAtk`/`adjustHp` exist on the record too but no
 * research pass pinned down whether/how they'd need combining with `atk`/`hp` — not used
 * here, consistent with not guessing at an unsourced combination rule); `className`/
 * `attribute` from the nested `svt: EntityBasic`, not the enemy record's own top level
 * (`QuestEnemy` has no top-level `className`/`attribute` fields); `traits` flattened to the
 * `ReadonlySet<number>` id-only shape every other trait field in this project already uses;
 * `npTurnLimit` from `chargeTurn` (research/08 §5, live-confirmed); `deathRate` direct
 * (research/08 §2's formula input); `currentNpTurns: 0` and `readyToNp: false` (research/08
 * §5's confirmed "starts at 0 unless a specific quest/enemy gimmick says otherwise" — no
 * gimmick-detection exists yet, so this is always the unconditional default); `activeBuffs:
 * []` — an enemy's `classPassive`/`addPassive` skills (`QuestEnemy.classPassive`) are NOT
 * auto-granted as buffs here, a known gap consistent with this project's scope: no general
 * skill/passive interpreter reads a `NiceSkill`'s raw `functions[]` automatically anywhere
 * yet (every `SkillEffect` this project models is still hand-constructed by a caller).
 */
export function buildEnemyInstance(waveEnemy: WaveEnemy): EnemyInstance {
  return {
    npcId: waveEnemy.npcId,
    atk: waveEnemy.atk,
    className: waveEnemy.svt.className,
    attribute: waveEnemy.svt.attribute,
    traits: new Set(waveEnemy.traits.map((trait) => trait.id)),
    currentHp: waveEnemy.hp,
    maxHp: waveEnemy.hp,
    activeBuffs: [],
    currentNpTurns: 0,
    npTurnLimit: waveEnemy.chargeTurn,
    deathRate: waveEnemy.deathRate,
    readyToNp: false,
  };
}
